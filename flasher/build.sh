#!/usr/bin/env bash
# Build the in-app factory flasher for a given ESPHome factory.bin and wrap it
# for SolaX's MQTT OTA.
#
#   SSID=<wifi ssid> PSK=<wifi psk> REPORT_URL=http://<this-host>:<port> \
#     flasher/build.sh <factory.bin> [out.ota.bin]
#
# REPORT_URL is where the dongle finds tools/ota_server.py (it downloads
# /factory.bin from it, uploads the 4 MB backup to it and polls /go on it).
# Plain http:// only, no trailing slash, reachable from the dongle's Wi-Fi.
#
# Steps:
#   1. tools/check_factory.py validates the factory image (ESPHome default 4 MB
#      layout, image ends before 0x110000, ...) and writes main/factory_expect.h
#      with EXP_LEN / EXP_MD5, which the flasher checks before writing anything;
#   2. main/secrets.h is generated from SSID / PSK / REPORT_URL (mode 600, git-ignored);
#   3. `idf.py build` runs in espressif/idf:v4.4.4 (IDF 5.x images do NOT boot
#      under the stock IDF 4.x bootloader, so the flasher must stay on 4.4);
#   4. tools/make_ota_image.py appends the whole-image CRC-16 trailer;
#   5. <out>.json records report_url / factory len+md5 for convert.py.
#
# The output contains your Wi-Fi PSK in clear text. Keep it to yourself.
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(dirname "$HERE")
IDF_IMAGE=${IDF_IMAGE:-espressif/idf:v4.4.4}

FACTORY=${1:?usage: SSID=.. PSK=.. REPORT_URL=http://host:port $0 <factory.bin> [out.ota.bin]}
OUT=${2:-$ROOT/build/flasher.ota.bin}
: "${SSID:?set SSID (Wi-Fi the dongle should join)}"
: "${PSK:?set PSK (Wi-Fi password)}"
: "${REPORT_URL:?set REPORT_URL, e.g. http://192.0.2.10:8080}"

if ! [[ $REPORT_URL =~ ^http://[A-Za-z0-9.-]+:[0-9]{1,5}$ ]]; then
  echo "REPORT_URL must look like http://<host>:<port> (no path, no trailing slash, no https)" >&2
  exit 1
fi
if (( ${#REPORT_URL} > 70 )); then
  echo "REPORT_URL too long (the flasher builds URLs in 96-byte buffers)" >&2; exit 1
fi
if (( ${#SSID} > 32 )) || (( ${#PSK} < 8 || ${#PSK} > 63 )); then
  echo "SSID must be <= 32 chars and PSK 8..63 chars (WPA2-PSK)" >&2; exit 1
fi

mkdir -p "$(dirname "$OUT")"

echo "== 1/5 checking $FACTORY"
python3 -I "$ROOT/tools/check_factory.py" "$FACTORY" --header "$HERE/main/factory_expect.h"

echo "== 2/5 generating main/secrets.h"
( umask 077
  python3 -I - "$HERE/main/secrets.h" <<'PY'
import os, sys
def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
with open(sys.argv[1], "w") as f:
    f.write("/* generated by flasher/build.sh - do not commit */\n")
    f.write(f"#define WSSID {c(os.environ['SSID'])}\n")
    f.write(f"#define WPASS {c(os.environ['PSK'])}\n")
    f.write(f"#define REPORT {c(os.environ['REPORT_URL'])}\n")
PY
)

echo "== 3/5 idf.py build in $IDF_IMAGE"
docker run --rm -u "$(id -u):$(id -g)" -e HOME=/tmp -e IDF_TARGET=esp32s2 \
  -v "$HERE":/project -w /project "$IDF_IMAGE" idf.py build

echo "== 4/5 wrapping for the SolaX MQTT OTA"
python3 -I "$ROOT/tools/make_ota_image.py" "$HERE/build/solax_flasher.bin" "$OUT"

echo "== 5/5 writing $OUT.json"
python3 -I - "$FACTORY" "$OUT" <<'PY'
import hashlib, json, os, sys
factory, out = sys.argv[1], sys.argv[2]
fb = open(factory, "rb").read()
meta = {"report_url": os.environ["REPORT_URL"], "factory": os.path.abspath(factory),
        "factory_len": len(fb), "factory_md5": hashlib.md5(fb).hexdigest(),
        "ota_image": os.path.abspath(out), "ota_len": os.path.getsize(out)}
open(out + ".json", "w").write(json.dumps(meta, indent=2) + "\n")
print(json.dumps(meta, indent=2))
PY
echo "done: $OUT"
