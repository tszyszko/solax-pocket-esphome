#!/usr/bin/env python3
"""Sanity-check an ESPHome firmware.factory.bin before the flasher is built against it.

The in-app flasher hard-codes ESPHome's default 4 MB ESP-IDF layout, so this checks:
  * the image starts at flash offset 0 (bootloader image magic 0xE9 at 0x1000),
  * the partition table at 0x8000 has otadata at 0x9000, app0 at 0x10000 and app1
    at 0x1D0000 (the flasher writes the app to one of these and may craft otadata),
  * 0x9000..0x10000 is all 0xFF in the file (the flasher's final MD5 assumes it),
  * an app image (0xE9) at 0x10000 that fits in app0,
  * the image is shorter than the stock ota_1 start (0x110000), so writing it can
    never touch a flasher running from SolaX ota_1.
Prints length + MD5 and, with --header, writes the C header the flasher includes
(EXP_LEN, EXP_MD5, and EXP_HEAD_MD5 = MD5 of the first 64 KB, which the flasher
holds in RAM after GO).

Example:
    python3 -I tools/check_factory.py build/factory.bin --header flasher/main/factory_expect.h
"""
import argparse
import hashlib
import json
import pathlib
import struct
import sys

EXPECT = {"otadata": (0x01, 0x00, 0x9000), "app0": (0x00, 0x10, 0x10000), "app1": (0x00, 0x11, 0x1D0000)}
STOCK_OTA1 = 0x110000


def partitions(img):
    out = []
    for off in range(0x8000, 0x9000, 32):
        e = img[off:off + 32]
        if e[:2] != b"\xaa\x50":
            break
        typ, sub, poff, size = e[2], e[3], *struct.unpack_from("<II", e, 4)
        label = e[12:28].split(b"\0")[0].decode(errors="replace")
        out.append((label, typ, sub, poff, size))
    return out


def check(img, serial=False):
    errs = []
    if len(img) < 0x10000 + 0x100:
        errs.append(f"too short ({len(img)} B) to be a factory image starting at 0x0")
        return errs, []
    if img[0x1000] != 0xE9:
        errs.append("no bootloader image (0xE9) at 0x1000: is this a factory.bin written at offset 0x0?")
    parts = partitions(img)
    by_label = {p[0]: p for p in parts}
    for label, (typ, sub, off) in EXPECT.items():
        p = by_label.get(label)
        if not p or (p[1], p[2], p[3]) != (typ, sub, off):
            errs.append(f"partition {label!r} is not type {typ}/{sub:#x} at {off:#x} (found {p})")
    if not serial and any(b != 0xFF for b in img[0x9000:0x10000]):
        errs.append("0x9000..0x10000 is not all 0xFF in the file (flasher MD5 check assumes it)")
    if img[0x10000] != 0xE9:
        errs.append("no app image (0xE9) at 0x10000")
    app0 = by_label.get("app0")
    if app0 and len(img) - 0x10000 > app0[4]:
        errs.append("app does not fit in app0")
    if not serial and len(img) > STOCK_OTA1:
        errs.append(f"image ends past 0x{STOCK_OTA1:x}: would overwrite a flasher running from stock ota_1")
    return errs, parts


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("factory", help="ESPHome firmware.factory.bin")
    ap.add_argument("--header", help="write EXP_LEN / EXP_MD5 to this C header")
    ap.add_argument("--json", action="store_true", help="print the result as JSON")
    ap.add_argument("--serial", action="store_true",
                    help="checks for a serial flash only (skip the flasher-specific FF/size rules)")
    a = ap.parse_args()

    img = pathlib.Path(a.factory).read_bytes()
    md5 = hashlib.md5(img).hexdigest()
    errs, parts = check(img, a.serial)
    if a.json:
        print(json.dumps({"len": len(img), "md5": md5, "errors": errs,
                          "partitions": [dict(zip(("label", "type", "subtype", "offset", "size"), p)) for p in parts]}))
    else:
        print(f"{a.factory}: {len(img)} B md5 {md5}")
        for label, typ, sub, off, size in parts:
            print(f"  {label:12s} type {typ:#04x}/{sub:#04x}  0x{off:06x}  {size:#x}")
        for e in errs:
            print(f"  ERROR: {e}")
    if errs:
        sys.exit(1)
    if a.header:
        pathlib.Path(a.header).write_text(
            "/* generated by tools/check_factory.py - do not edit */\n"
            f"/* {pathlib.Path(a.factory).name} */\n"
            f"#define EXP_LEN {len(img)}\n"
            f'#define EXP_MD5 "{md5}"\n'
            f'#define EXP_HEAD_MD5 "{hashlib.md5(img[:0x10000]).hexdigest()}"  /* file 0x0..0x10000 */\n')
        if not a.json:
            print(f"wrote {a.header}")


if __name__ == "__main__":
    main()
